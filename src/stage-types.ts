import type { Segment } from './camera.ts';
import type { LandmarkId } from './reach.ts';

export type Fixture = 'stack' | 'draft' | 'boss' | 'pursuit' | LandmarkId;
export type StageOptions = {
  seed: number;
  view: Segment | null;
  fixture: Fixture | null;
  time: number | null;
  autoplay: boolean;
  touch: boolean;
};
export type DraftId = 'twin-2' | 'twin-3' | 'pods-2' | 'twin-damage' | 'pods-damage';
export type Outcome = 'clear' | 'timeout' | 'lost';
export type ManeuverKind = 'immelmann' | 'split-s' | 'cobra' | 'j-turn';
export type Maneuver = {
  kind: ManeuverKind;
  elapsed: number;
  yaw: number;
  altitude: number;
  exitAltitude: number;
  speed: number;
};
export type StageInput = {
  turn?: number;
  climb?: number;
  maneuver?: ManeuverKind;
  boost?: boolean;
  bomb?: boolean;
  toggleView?: boolean;
  start?: boolean;
  pause?: boolean;
  pick?: DraftId;
};

export type Point = { x: number; z: number };
export type Position = Point & { alt: number };
export type Ground = (x: number, z: number) => number;
export type Band = 0 | 1 | 2;
export type Enemy = Position & {
  id: number;
  kind: 'patrol' | 'interceptor';
  hp: number;
  yaw: number;
  vx: number;
  vz: number;
  bank: number;
  shotAt: number;
  hitUntil: number;
  shotDown: boolean;
  band: Band;
  offset: number;
  maneuverAt: number;
  maneuver: { phase: 'warning' | 'diving'; band: Band; diveAt: number } | null;
  course?: { target: Point; pass?: Point; speed: number; until: number };
};
export type Pickup = Position & { id: number; xp: number; born: number };
export type Shot = Position & {
  vx: number;
  vz: number;
  life: number;
  damage: number;
  kind: 'twin' | 'pods' | 'hostile';
  volley: number;
  nearMiss: boolean;
  lockId: number | null;
};
export type RearBomb = Position & { born: number; vx: number; vz: number };
export type Effect = Position & (
  { kind: 'hit' | 'burst' | 'bomb-blast'; life: number } |
  { kind: 'miss'; life: number; delta: number; vx: number; vz: number }
);
export type WeakPoint = Position & {
  id: number;
  kind: 'pod' | 'core';
  band: Band;
  hp: number;
  maxHp: number;
  hits: number;
  window: number;
  vx: number;
  vz: number;
};
export type Boss = {
  x: number;
  z: number;
  alt: number;
  weakPoints: WeakPoint[];
  orbitAngle: number;
  orbitStartTick: number;
  index: number;
  exposeTick: number;
  changedTick: number;
  shotAt: number;
};
export type Lock = { id: number; progress: number; ready: boolean };
export type StageState = {
  phase: 'title' | 'playing' | 'draft' | Outcome;
  paused: boolean;
  resultPending: Outcome | null;
  seed: number;
  rng: number;
  nextId: number;
  nextVolley: number;
  tick: number;
  nextWave: number;
  view: Segment;
  initialView: Segment | null;
  wipe: number;
  viewTag: number;
  arena: { x: number; z: number; radius: number };
  boundaryWarning: boolean;
  player: { x: number; z: number; altitude: number; yaw: number; bank: number };
  speed: number;
  climbRate: number;
  hull: number;
  maxHull: number;
  hitsTaken: number;
  rank: 'S' | 'A' | 'B' | 'C' | null;
  invulnerability: number;
  boost: number;
  boosting: boolean;
  bombs: number;
  bombReadyAt: number;
  bombReloadAt: number | null;
  rearBombs: RearBomb[];
  maneuver: Maneuver | null;
  maneuverReadyAt: number;
  xp: number;
  level: 1 | 2 | 3;
  salvage: number;
  salvageBands: [number, number, number];
  draft: DraftId[];
  picks: DraftId[];
  graceUntil: number;
  boostRelease: boolean;
  twinRank: 1 | 2 | 3;
  podRank: 1 | 2;
  twinDamage: number;
  podDamage: number;
  twinAt: number;
  podsAt: number;
  score: number;
  enemies: Enemy[];
  pickups: Pickup[];
  shots: Shot[];
  effects: Effect[];
  boss: Boss | null;
  lock: Lock | null;
  wrongLayer: { id: number; since: number } | null;
  altitudeHint: { delta: number } | null;
};
